export function nonceReplacementMiddleware() {
  return `<?php

namespace App\\Http\\Middleware;

use Closure;
use Illuminate\\Http\\Request;
use Symfony\\Component\\HttpFoundation\\Response;

// ${GENERATED}
// A full-page cache stores HTML with one nonce and serves it to everyone, which makes the nonce guessable.
// SecureHeadersMiddleware renders a placeholder instead, and this middleware, registered outside the cache,
// replaces it with a fresh nonce in the headers and body of every response, cached or not.
// The placeholder is derived from APP_KEY, so injected markup cannot know it and get rewritten into a valid nonce.
class ReplaceCachedCspNonce
{
    private const HEADERS = ['Content-Security-Policy', 'Content-Security-Policy-Report-Only'];

    public static function placeholder(): string
    {
        return hash_hmac('sha256', 'csp-cached-page-nonce', (string) config('app.key'));
    }

    public function handle(Request $request, Closure $next): Response
    {
        $response = $next($request);
        $placeholder = self::placeholder();
        $nonce = base64_encode(random_bytes(16));

        foreach (self::HEADERS as $header) {
            if ($response->headers->has($header)) {
                $response->headers->set($header, str_replace($placeholder, $nonce, (string) $response->headers->get($header)));
            }
        }

        $content = $response->getContent();
        if (is_string($content) && str_contains($content, $placeholder)) {
            $response->setContent(str_replace($placeholder, $nonce, $content));
        }

        return $response;
    }
}
`;
}

// ── spatie/laravel-csp v3 ───────────────────────────────────────────────────
const SPATIE_DIRECTIVES = {
  'default-src': 'DEFAULT', 'script-src': 'SCRIPT', 'style-src': 'STYLE', 'style-src-attr': 'STYLE_ATTR', 'font-src': 'FONT',
  'img-src': 'IMG', 'media-src': 'MEDIA', 'frame-src': 'FRAME', 'connect-src': 'CONNECT', 'worker-src': 'WORKER',
  'manifest-src': 'MANIFEST', 'form-action': 'FORM_ACTION', 'object-src': 'OBJECT', 'base-uri': 'BASE', 'frame-ancestors': 'FRAME_ANCESTORS',
};
const SPATIE_KEYWORDS = { "'self'": 'Keyword::SELF', "'none'": 'Keyword::NONE', "'unsafe-eval'": 'Keyword::UNSAFE_EVAL', "'unsafe-inline'": 'Keyword::UNSAFE_INLINE' };

function spatieCalls(directives, indent) {
  const pad = ' '.repeat(indent);
  const calls = [];
  for (const d of directives) {
    const constant = SPATIE_DIRECTIVES[d.name];
    if (!constant) continue;
    const values = d.sources.filter(s => s !== NONCE).map(s => SPATIE_KEYWORDS[s] ?? phpLiteral(s));
    if (values.length) calls.push(`${pad}->add(Directive::${constant}, [${values.join(', ')}])`);
    if (d.sources.includes(NONCE)) calls.push(`${pad}->addNonce(Directive::${constant})`);
  }
  return calls;
}

function spatieNotes(state) {
  const skip = skippedPaths(state);
  return (skip.length ? `\n// Leave the CSP off for ${skip.join(', ')}: those dashboards ship inline scripts without a nonce.` : '') + embedNote(state, '//');
}

export function spatiePreset(state) {
  const prod = buildDirectives(state, 'production');
  const local = buildDirectives(state, 'local');
  const extra = local.map(d => ({ ...d, sources: d.sources.filter(s => !(prod.find(p => p.name === d.name)?.sources ?? []).includes(s)) }))
    .filter(d => d.sources.length);
  const localBlock = extra.length
    ? `

        if (app()->environment('local')) {
            $policy
${spatieCalls(extra, 16).join('\n')};

            return;
        }`
    : '';
  return `<?php

namespace App\\Support;

use Spatie\\Csp\\Directive;
use Spatie\\Csp\\Keyword;
use Spatie\\Csp\\Policy;
use Spatie\\Csp\\Preset;
use Spatie\\Csp\\Value;

// ${GENERATED}
// Register in config/csp.php under ${state.reportOnly ? "'report_only_presets'" : "'presets'"}.${spatieNotes(state)}${state.reporting ? `
// Reporting: set 'report_uri' => '${REPORT_PATH}', and 'report_to' => '${REPORT_GROUP}' with a matching 'reporting_endpoints' entry.` : ''}
class AppCspPreset implements Preset
{
    public function configure(Policy $policy): void
    {
        $policy
${spatieCalls(prod, 12).join('\n')};${localBlock}

        $policy->add(Directive::UPGRADE_INSECURE_REQUESTS, Value::NO_VALUE);
    }
}
`;
}

// ── Web server and meta tag ─────────────────────────────────────────────────
function embedNote(state, prefix) {
  if (!state.embeds.length) return '';
  return `\n${prefix} Embedding exceptions need their own location block with frame-ancestors 'self' plus:\n` +
    state.embeds.map(e => `${prefix}   /${e.path}: ${e.origins.join(' ')}`).join('\n');
}

const NGINX_PLACEHOLDER = /^[A-Za-z0-9]{8,64}$/;

// `placeholder` must be a secret random token: whatever HTML carries it gets the real nonce.
export function nginxConfig(state, env = 'production', placeholder) {
  if (!NGINX_PLACEHOLDER.test(String(placeholder ?? ''))) throw new Error('nginxConfig needs a random placeholder of 8 to 64 letters and digits');
  const value = headerValue(state, env).replaceAll(NONCE, "'nonce-$request_id'");
  const reporting = state.reporting ? `\nadd_header Reporting-Endpoints '${REPORT_GROUP}="https://$host${REPORT_PATH}"' always;` : '';
  return `# ${GENERATED}
# nginx has no nonce of its own, so this uses $request_id (unique per request) as the nonce.
# Write nonce="${placeholder}" on inline <script> and <style> tags; sub_filter swaps in the real value.
# Keep ${placeholder} secret and unique to your site: any HTML that carries it, injected or not, gets the real nonce.
# When proxying, also set: proxy_set_header Accept-Encoding "";  (sub_filter cannot rewrite compressed bodies)${embedNote(state, '#')}
sub_filter_once off;
sub_filter_types text/html;
sub_filter '${placeholder}' $request_id;
add_header ${headerName(state)} "${value}" always;${reporting}`;
}

export function apacheConfig(state, env = 'production') {
  const value = headerValue(state, env).replaceAll(` ${NONCE}`, '');
  const reporting = state.reporting ? `\nHeader always set Reporting-Endpoints "expr=${REPORT_GROUP}=\\"https://%{HTTP_HOST}${REPORT_PATH}\\""` : '';
  return `# ${GENERATED}
# Apache cannot generate a per-request nonce, so this policy has none: every inline <script> and <style>
# is blocked. Move them into files, or send the header from the Laravel middleware instead.${embedNote(state, '#')}
Header always set ${headerName(state)} "${value}"${reporting}`;
}

const META_UNSUPPORTED = ['frame-ancestors', 'report-uri', 'report-to'];

export function metaTag(state, env = 'production') {
  const value = policyString(buildDirectives(state, env).filter(d => !META_UNSUPPORTED.includes(d.name)))
    .replaceAll(NONCE, "'nonce-{{ $cspNonce }}'");
  const reportOnly = state.reportOnly ? '\n{{-- A meta tag cannot be report-only: browsers ignore Content-Security-Policy-Report-Only here, so this tag enforces. --}}' : '';
  return `{{-- ${GENERATED} --}}
{{-- A meta tag cannot set frame-ancestors or send reports. Prefer the HTTP header. --}}${reportOnly}
<meta http-equiv="Content-Security-Policy" content="${value}">`;
}
