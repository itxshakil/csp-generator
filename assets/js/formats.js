// Every output format as plain text. Pure functions: the UI escapes before rendering.
import { buildDirectives, policyString, headerName, skippedPaths, NONCE, REPORT_PATH, REPORT_GROUP, SIZE_WARN, SIZE_OVER } from './policy.js';

const GENERATED = 'Generated by https://csp-generator.shakiltech.com';

export function headerValue(state, env = 'production', dirs = buildDirectives(state, env)) {
  return policyString(dirs);
}

// ── PHP helpers ─────────────────────────────────────────────────────────────
function phpLiteral(source) {
  if (source === NONCE) return `"${NONCE}"`;
  if (/^'[a-z-]+'$/.test(source)) return `"${source}"`;
  return `'${source.replace(/[\\']/g, '\\$&')}'`;
}

// A comment can never close the PHP block or span lines.
const comment = reasons => reasons.join('; ').replace(/\?>/g, '? >').replace(/[\r\n]+/g, ' ');

// Merges the production and local lists into one sequence tagged both, prod or local, keeping each list's order.
function mergeSources(prod, local) {
  const out = [];
  let i = 0;
  let j = 0;
  while (i < prod.length || j < local.length) {
    if (i < prod.length && j < local.length && prod[i] === local[j]) { out.push([prod[i], 'both']); i++; j++; }
    // A source that is not ahead in `local` is production-only here, even if it appears earlier there. That keeps both lists moving.
    else if (i < prod.length && local.indexOf(prod[i], j) === -1) out.push([prod[i++], 'prod']);
    else out.push([local[j++], 'local']);
  }
  return out;
}

function mergeNames(prod, local) {
  const names = prod.map(d => d.name);
  local.forEach((d, idx) => {
    if (names.includes(d.name)) return;
    const before = idx > 0 ? names.indexOf(local[idx - 1].name) : -1;
    names.splice(before + 1, 0, d.name);
  });
  return names;
}

function phpSourceLines(prodDir, localDir, indent) {
  const pad = ' '.repeat(indent);
  const reasonsOf = s => prodDir?.reasons[s] ?? localDir?.reasons[s] ?? [];
  const line = (s, extra) => `${pad}${extra}${phpLiteral(s)}, // ${comment(reasonsOf(s))}`;
  const runs = [];
  for (const [source, tag] of mergeSources(prodDir?.sources ?? [], localDir?.sources ?? [])) {
    if (runs.length && runs.at(-1).tag === tag) runs.at(-1).sources.push(source);
    else runs.push({ tag, sources: [source] });
  }
  return runs.flatMap(({ tag, sources }) => {
    if (tag === 'both') return sources.map(s => line(s, ''));
    const inner = sources.map(s => line(s, '    '));
    return tag === 'local'
      ? [`${pad}...($local ? [`, ...inner, `${pad}] : []),`]
      : [`${pad}...($local ? [] : [`, ...inner, `${pad}]),`];
  });
}

function phpDirectives(state) {
  const prod = buildDirectives(state, 'production');
  const local = buildDirectives(state, 'local');
  const lines = [];
  for (const name of mergeNames(prod, local)) {
    const p = prod.find(d => d.name === name);
    const l = local.find(d => d.name === name);
    if (name === 'frame-ancestors') {
      lines.push(`            'frame-ancestors' => $embedOrigins === null ? ["'none'"] : ["'self'", ...$embedOrigins],`);
      continue;
    }
    if ((p ?? l).sources.length === 0) {
      lines.push(`            '${name}' => ${p && l ? '[]' : p ? '$local ? null : []' : '$local ? [] : null'},`);
      continue;
    }
    const body = phpSourceLines(p, l, 16);
    if (p && l) lines.push(`            '${name}' => [`, ...body, '            ],');
    else lines.push(`            '${name}' => ${p ? '$local ? null : [' : '! $local ? null : ['}`, ...body, '            ],');
  }
  return lines.join('\n');
}

function phpStringArray(list) {
  return `[${list.map(phpLiteral).join(', ')}]`;
}

// ── Laravel ─────────────────────────────────────────────────────────────────
export function laravelMiddleware(state) {
  const header = headerName(state);
  const skip = skippedPaths(state);
  const embeds = state.embeds.map(e => `        ${phpLiteral(e.path)} => ${phpStringArray(e.origins)},`);
  const nonceLine = state.fullPageCache
    ? `        // Full-page cache: render a secret placeholder; ReplaceCachedCspNonce swaps in a fresh nonce on every response.
        $nonce = ReplaceCachedCspNonce::placeholder();`
    : '        $nonce = base64_encode(random_bytes(16));';
  const reporting = state.reporting
    ? `\n        $response->headers->set('Reporting-Endpoints', '${REPORT_GROUP}="' . url('${REPORT_PATH}') . '"');`
    : '';
  return `<?php

namespace App\\Http\\Middleware;

use Closure;
use Illuminate\\Http\\Request;
use Illuminate\\Support\\Facades\\View;
use Illuminate\\Support\\Facades\\Vite;
use Symfony\\Component\\HttpFoundation\\Response;

// ${GENERATED}
class SecureHeadersMiddleware
{
    /** Paths other sites may frame, with the sites allowed to frame them. */
    private const EMBEDS = [${embeds.length ? '\n' + embeds.join('\n') + '\n    ' : ''}];

    /** Dashboards that ship their own inline scripts, so they get no CSP. */
    private const SKIP_CSP = ${phpStringArray(skip)};

    public function handle(Request $request, Closure $next): Response
    {
${nonceLine}
        Vite::useCspNonce($nonce);
        View::share('cspNonce', $nonce);

        $response = $next($request);

        $response->headers->set('X-Content-Type-Options', 'nosniff');
        $response->headers->set('Referrer-Policy', 'strict-origin-when-cross-origin');
        if (! app()->environment('local')) {
            // Add includeSubDomains (and preload) only once every subdomain serves HTTPS.
            $response->headers->set('Strict-Transport-Security', 'max-age=31536000');
        }

        if (self::SKIP_CSP !== [] && $request->is(...self::SKIP_CSP)) {
            return $response;
        }

        $embedOrigins = $this->embedOrigins($request);
        if ($embedOrigins === null) {
            $response->headers->set('X-Frame-Options', 'DENY');
        }

        $response->headers->set('${header}', $this->policy($nonce, $embedOrigins));${reporting}

        return $response;
    }

    /** @return list<string>|null */
    private function embedOrigins(Request $request): ?array
    {
        foreach (self::EMBEDS as $pattern => $origins) {
            if ($request->is($pattern)) {
                return $origins;
            }
        }

        return null;
    }

    /** @param list<string>|null $embedOrigins */
    private function policy(string $nonce, ?array $embedOrigins): string
    {
        $local = app()->environment('local');

        $directives = [
${phpDirectives(state)}
        ];

        $parts = [];
        foreach ($directives as $name => $sources) {
            if ($sources !== null) {
                $parts[] = $sources === [] ? $name : $name . ' ' . implode(' ', $sources);
            }
        }

        return implode('; ', $parts);
    }
}
`;
}

export function laravelBootstrap(state) {
  const prepend = state.fullPageCache
    ? `
        // Must run outside your page cache middleware, so it sees cached responses too.
        $middleware->web(prepend: [
            \\App\\Http\\Middleware\\ReplaceCachedCspNonce::class,
        ]);`
    : '';
  return `// bootstrap/app.php
->withMiddleware(function (Middleware $middleware) {${prepend}
        $middleware->web(append: [
            \\App\\Http\\Middleware\\SecureHeadersMiddleware::class,
        ]);
    })`;
}

export function bladeSnippets(state) {
  const has = id => state.stack.includes(id);
  const lines = [
    '{{-- @vite adds the nonce for you once Vite::useCspNonce() has run --}}',
    "@vite(['resources/css/app.css', 'resources/js/app.js'])",
    '',
    '<script nonce="{{ $cspNonce }}">...</script>',
    '<style nonce="{{ $cspNonce }}">...</style>',
  ];
  if (has('livewire') || has('filament')) lines.push('', '{{-- Livewire 3 --}}', "@livewireScriptConfig(['nonce' => $cspNonce])");
  if (has('inertia')) lines.push('', '{{-- Inertia with Ziggy --}}', '@routes(nonce: $cspNonce)');
  if (has('alpineCsp')) lines.push('', "{{-- resources/js/app.js: import Alpine from '@alpinejs/csp' --}}");
  return lines.join('\n');
}

