export function reportController() {
  return `<?php

namespace App\\Http\\Controllers;

use Illuminate\\Http\\Request;
use Illuminate\\Http\\Response;
use Illuminate\\Support\\Facades\\Log;

// ${GENERATED}
class CspReportController
{
    /** Browser extensions inject code your policy rightly blocks. Their reports are noise. */
    private const NOISE = ['chrome-extension:', 'moz-extension:', 'safari-web-extension:', 'safari-extension:', 'about:'];

    private const MAX_REPORTS = 10;

    public function __invoke(Request $request): Response
    {
        foreach ($this->reports($request) as $report) {
            if (! $this->isNoise($report)) {
                Log::warning('CSP violation', $report);
            }
        }

        return response()->noContent();
    }

    /** @return list<array<string, mixed>> */
    private function reports(Request $request): array
    {
        $body = json_decode($request->getContent(), true);
        if (! is_array($body)) {
            return [];
        }

        // report-uri sends {"csp-report": {...}}.
        if (isset($body['csp-report']) && is_array($body['csp-report'])) {
            return [$body['csp-report']];
        }

        // report-to sends a list of {"type": "csp-violation", "body": {...}}.
        $reports = [];
        foreach (array_slice($body, 0, self::MAX_REPORTS) as $item) {
            if (is_array($item) && ($item['type'] ?? null) === 'csp-violation' && is_array($item['body'] ?? null)) {
                $reports[] = $item['body'];
            }
        }

        return $reports;
    }

    /** @param array<string, mixed> $report */
    private function isNoise(array $report): bool
    {
        foreach (['blocked-uri', 'blockedURL', 'source-file', 'sourceFile'] as $key) {
            $value = is_string($report[$key] ?? null) ? $report[$key] : '';
            foreach (self::NOISE as $prefix) {
                if (str_starts_with($value, $prefix)) {
                    return true;
                }
            }
        }

        return false;
    }
}
`;
}

